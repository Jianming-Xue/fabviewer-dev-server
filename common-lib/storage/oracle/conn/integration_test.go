// oracleGooseStore 是 goose 的 Oracle 方言 Store 全量实现（goose v3 未内置
// Oracle dialect）。不使用 NewStoreFromQuerier 适配层的原因（真实库集成测试
// 抓出）：适配层的 Insert 把 Go bool 直接绑定为 is_applied，而 godror 对非
// PL/SQL 语句按 DPI BOOLEAN 绑定，写入 VARCHAR2 失败；且 Oracle DDL 隐式
// 提交会让"建表+插 0 号记录"事务半途失败后残留空表（ListMigrations 为空 →
// goose 报 missing zero version migration）。因此自行实现 Store，
// is_applied 一律以 "1"/"0" 字符串绑定与读回。
type oracleGooseStore struct{ tableName string }

var _ database.Store = oracleGooseStore{}

// Tablename 实现 database.Store。
func (s oracleGooseStore) Tablename() string { return s.tableName }

// CreateVersionTable 实现 database.Store。
func (s oracleGooseStore) CreateVersionTable(ctx context.Context, db database.DBTxConn) error {
	_, err := db.ExecContext(ctx, fmt.Sprintf(`CREATE TABLE %s (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id NUMBER(19) NOT NULL,
  is_applied VARCHAR2(1) NOT NULL,
  tstamp TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)`, s.tableName))
	return err
}

// Insert 实现 database.Store。goose 恒以 IsApplied=true 调用，绑定为 "1"。
func (s oracleGooseStore) Insert(ctx context.Context, db database.DBTxConn, req database.InsertRequest) error {
	_, err := db.ExecContext(ctx,
		fmt.Sprintf("INSERT INTO %s (version_id, is_applied) VALUES (:1, :2)", s.tableName),
		req.Version, "1")
	return err
}

// Delete 实现 database.Store。
func (s oracleGooseStore) Delete(ctx context.Context, db database.DBTxConn, version int64) error {
	_, err := db.ExecContext(ctx,
		fmt.Sprintf("DELETE FROM %s WHERE version_id = :1", s.tableName), version)
	return err
}

// GetMigration 实现 database.Store，未找到返回 database.ErrVersionNotFound。
func (s oracleGooseStore) GetMigration(
	ctx context.Context, db database.DBTxConn, version int64,
) (*database.GetMigrationResult, error) {
	row := db.QueryRowContext(ctx, fmt.Sprintf(
		"SELECT tstamp, is_applied FROM %s WHERE version_id = :1 "+
			"ORDER BY tstamp DESC FETCH FIRST 1 ROWS ONLY", s.tableName), version)
	var r database.GetMigrationResult
	var applied string
	if err := row.Scan(&r.Timestamp, &applied); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil, database.ErrVersionNotFound
		}
		return nil, err
	}
	r.IsApplied = applied == "1"
	return &r, nil
}

// GetLatestVersion 实现 database.Store，无记录返回 database.ErrVersionNotFound。
func (s oracleGooseStore) GetLatestVersion(ctx context.Context, db database.DBTxConn) (int64, error) {
	var v sql.NullInt64
	err := db.QueryRowContext(ctx,
		fmt.Sprintf("SELECT MAX(version_id) FROM %s", s.tableName)).Scan(&v)
	if err != nil {
		return 0, err
	}
	if !v.Valid {
		return 0, database.ErrVersionNotFound
	}
	return v.Int64, nil
}

// ListMigrations 实现 database.Store，按 id 倒序。
func (s oracleGooseStore) ListMigrations(
	ctx context.Context, db database.DBTxConn,
) ([]*database.ListMigrationsResult, error) {
	rows, err := db.QueryContext(ctx, fmt.Sprintf(
		"SELECT version_id, is_applied FROM %s ORDER BY id DESC", s.tableName))
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []*database.ListMigrationsResult
	for rows.Next() {
		var r database.ListMigrationsResult
		var applied string
		if err := rows.Scan(&r.Version, &applied); err != nil {
			return nil, err
		}
		r.IsApplied = applied == "1"
		out = append(out, &r)
	}
	return out, rows.Err()
}

// TableExists 是 goose 的可选接口：返回 '1'/'0' 字符串而非数字——godror 把
// NUMBER 列返回为 godror.Number，无法被 driver.Bool 转换进 bool。
func (s oracleGooseStore) TableExists(ctx context.Context, db database.DBTxConn) (bool, error) {
	var v string
	err := db.QueryRowContext(ctx, fmt.Sprintf(
		"SELECT CASE WHEN COUNT(*) > 0 THEN '1' ELSE '0' END "+
			"FROM user_tables WHERE table_name = '%s'", s.tableName)).Scan(&v)
	if err != nil {
		return false, err
	}
	return v == "1", nil
}

// integrationDSN 解析 user/password@host[:port]/service 环境变量。
func integrationDSN(t *testing.T, dsn string) config.Config {
	t.Helper()
	cred, addr, ok := strings.Cut(strings.TrimPrefix(dsn, "oracle://"), "@")
	require.True(t, ok, "DSN 应为 user/password@host[:port]/service")
	user, password, ok := strings.Cut(cred, "/")
	require.True(t, ok && user != "" && password != "", "DSN 凭据应为 user/password")
	hostPort, service, ok := strings.Cut(addr, "/")
	require.True(t, ok && hostPort != "" && service != "", "DSN 缺少 /service 段")
	host, portStr, hasPort := strings.Cut(hostPort, ":")
	port := config.DefaultPort
	if hasPort {
		p, err := strconv.Atoi(portStr)
		require.NoError(t, err, "端口非法")
		port = p
	}
	return config.Config{
		User: user, Password: password, Host: host, Port: port, ServiceName: service,
		SessionParams: map[string]string{"NLS_DATE_FORMAT": "YYYY-MM-DD HH24:MI:SS"},
	}
}

// 验收线：Open → Ping → goose 迁移 → GORM CRUD → CallProc 标量 →
// CallProc 游标 → GORM 事务内 CallProcTx → Close。
func TestOracleIntegration(t *testing.T) {
	dsn := os.Getenv("COMMON_LIB_ORACLE_DSN")
	if dsn == "" {
		t.Skip("未设置 COMMON_LIB_ORACLE_DSN，跳过 Oracle 集成测试")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()

	db, err := Open(ctx, integrationDSN(t, dsn))
	require.NoError(t, err)
	defer func() { require.NoError(t, db.Close()) }()
	require.NoError(t, db.Ping(ctx), "探活 SELECT 1 FROM DUAL")

	migrateUp(t, ctx, db)
	demoGormCRUDIntegration(t, ctx, db)
	demoProcIntegration(t, ctx, db)
	demoTxIntegration(t, ctx, db)
}

// migrateUp 应用 testdata/migrations/oracle 下的全部迁移（幂等）。
func migrateUp(t *testing.T, ctx context.Context, db *DB) {
	t.Helper()
	store := oracleGooseStore{tableName: "GOOSE_DB_VERSION"}
	fsys := os.DirFS(filepath.Join("testdata", "migrations", "oracle"))
	provider, err := goose.NewProvider(goose.DialectCustom, db.SQL(), fsys, goose.WithStore(store))
	require.NoError(t, err)
	if _, err := provider.Up(ctx); err != nil {
		t.Fatalf("goose 迁移失败: %v", err)
	}
}

// gadgetIT 是 GORM CRUD 集成演示模型。
type gadgetIT struct {
	ID   int64
	Name string
}

// TableName 固定迁移建出的演示表。
func (gadgetIT) TableName() string { return "CL_DEMO_GADGETS" }

// demoGormCRUDIntegration 走 GORM 出口完成增查改删。
func demoGormCRUDIntegration(t *testing.T, ctx context.Context, db *DB) {
	t.Helper()
	g := db.GORM().WithContext(ctx)
	require.NoError(t, g.Where("1 = 1").Delete(&gadgetIT{}).Error, "清空演示表")
	for i := int64(1); i <= 3; i++ {
		require.NoError(t, g.Create(&gadgetIT{ID: i, Name: "g-" + strconv.FormatInt(i, 10)}).Error)
	}
	var got gadgetIT
	require.NoError(t, g.Where("ID = ?", int64(2)).First(&got).Error)
	assert.Equal(t, "g-2", got.Name)
	require.NoError(t, g.Model(&got).Update("NAME", "g-2-updated").Error)
	require.NoError(t, g.Delete(&gadgetIT{}, int64(3)).Error)

	var total int64
	require.NoError(t, g.Model(&gadgetIT{}).Count(&total).Error)
	assert.Equal(t, int64(2), total)
}

// demoProcIntegration 验证标量 OUT 与游标 OUT。
func demoProcIntegration(t *testing.T, ctx context.Context, db *DB) {
	t.Helper()
	var total int64
	require.NoError(t, db.CallProc(ctx, "CL_DEMO_SETTLE", 10, Out(&total)))
	assert.Equal(t, int64(30), total, "1*10 + 2*10")

	var cur Cursor
	require.NoError(t, db.CallProc(ctx, "CL_DEMO_LIST", OutCursor(&cur)))
	defer func() { require.NoError(t, cur.Close()) }()

	cols, err := cur.Columns()
	require.NoError(t, err)
	assert.Equal(t, []string{"ID", "NAME"}, cols)

	type row struct {
		id   int64
		name string
	}
	var rows []row
	for cur.Next() {
		var r row
		require.NoError(t, cur.Scan(&r.id, &r.name))
		rows = append(rows, r)
	}
	require.NoError(t, cur.Err())
	assert.Equal(t, []row{{1, "g-1"}, {2, "g-2-updated"}}, rows)
}

// demoTxIntegration 验证 GORM 事务与存储过程同事务（db-gorm-transactions）。
func demoTxIntegration(t *testing.T, ctx context.Context, db *DB) {
	t.Helper()
	err := db.GORM().WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		if err := tx.Create(&gadgetIT{ID: 99, Name: "tx-row"}).Error; err != nil {
			return bizerror.NewError(bizerror.CodeDB, "事务内 Create").AttachError(err, nil)
		}
		ex, err := FromGorm(tx)
		if err != nil {
			return err
		}
		var total int64
		if err := CallProcTx(ctx, ex, "CL_DEMO_SETTLE", 1, Out(&total)); err != nil {
			return err
		}
		if total != 102 { // 1 + 2 + 99，过程与 DML 同事务才可见
			return bizerror.NewError(bizerror.CodeDB, "事务内过程聚合非预期: {0}", total)
		}
		return nil
	})
	require.NoError(t, err)
}
