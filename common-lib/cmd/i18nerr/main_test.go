package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// writeMsgFile 在临时目录写一份消息文件。
func writeMsgFile(t *testing.T, dir, name, content string) {
	t.Helper()
	require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600))
}

const enFile = `package usererrors

var MessagesEn = map[string]string{
	"UserNotFound": "user {0} not found",
	"UserDisabled": "user disabled",
}
`

const zhFile = `package usererrors

var MessagesZh = map[string]string{
	"UserNotFound": "用户不存在",
	"UserDisabled": "账号已禁用",
}
`

func TestRunGeneratesVarsAndRegisterAll(t *testing.T) {
	dir := t.TempDir()
	writeMsgFile(t, dir, "messages_en.go", enFile)
	writeMsgFile(t, dir, "messages_zh.go", zhFile)
	writeMsgFile(t, dir, "doc.go", "package usererrors\n")       // 非消息文件忽略
	writeMsgFile(t, dir, "errors_gen.go", "// 旧的生成物，重生成前存在也不影响") // 自身被忽略

	require.NoError(t, run(dir, "usererrors", "en", "errors_gen.go"))

	src, err := os.ReadFile(filepath.Join(dir, "errors_gen.go"))
	require.NoError(t, err)
	got := string(src)
	assert.Contains(t, got, "// Code generated by i18nerr from messages_*.go. DO NOT EDIT.")
	assert.Contains(t, got, "package usererrors")
	assert.Contains(t, got, `CodeUserDisabled = fverr.Code("UserDisabled")`)
	assert.Contains(t, got, `CodeUserNotFound = fverr.Code("UserNotFound")`)
	assert.Contains(t, got, "var ErrorCode = newDictionary()")
	assert.Contains(t, got, "func New(ctx context.Context, code fverr.Code) *fverr.FvError {")
	assert.Contains(t, got, "return fverr.NewError(code, ErrorCode.T(ctx, string(code)))")
	assert.Contains(t, got, "func NewUserNotFound(ctx context.Context) *fverr.FvError { return New(ctx, CodeUserNotFound) }")
	assert.Contains(t, got, `b.Register(i18n.Language("en"), MessagesEn)`)
	assert.Contains(t, got, `b.Register(i18n.Language("zh"), MessagesZh)`)
}

func TestRunErrors(t *testing.T) {
	tests := []struct {
		name    string
		files   map[string]string
		pkg     string
		def     string
		wantErr string
	}{
		{
			name:    "缺必填参数",
			files:   nil,
			pkg:     "",
			def:     "en",
			wantErr: "-pkg/-default",
		},
		{
			name:    "目录无消息文件",
			files:   map[string]string{"doc.go": "package p\n"},
			pkg:     "p",
			def:     "en",
			wantErr: "未找到 messages_",
		},
		{
			name: "缺默认语言文件",
			files: map[string]string{
				"messages_zh.go": zhFile,
			},
			pkg:     "p",
			def:     "en",
			wantErr: "缺少默认语言文件",
		},
		{
			name: "key 非导出标识符形",
			files: map[string]string{
				"messages_en.go": "package p\n\nvar M = map[string]string{\"userNotFound\": \"x\"}\n",
			},
			pkg:     "p",
			def:     "en",
			wantErr: "userNotFound",
		},
		{
			name: "每文件只允许一个消息 map",
			files: map[string]string{
				"messages_en.go": "package p\n\nvar (\n\tA = map[string]string{\"K\": \"v\"}\n\tB = map[string]string{\"K2\": \"v2\"}\n)\n",
			},
			pkg:     "p",
			def:     "en",
			wantErr: "只允许一个消息 map",
		},
		{
			name: "值不支持拼接表达式",
			files: map[string]string{
				"messages_en.go": "package p\n\nvar M = map[string]string{\"K\": \"a\" + \"b\"}\n",
			},
			pkg:     "p",
			def:     "en",
			wantErr: "仅支持字符串字面量",
		},
		{
			name: "key 重复",
			files: map[string]string{
				"messages_en.go": "package p\n\nvar M = map[string]string{\"K\": \"a\", \"K\": \"b\"}\n",
			},
			pkg:     "p",
			def:     "en",
			wantErr: "重复",
		},
		{
			name: "同一语言两个文件（归一化后相同）",
			files: map[string]string{
				"messages_zh_cn.go": zhFile,
				"messages_zh-CN.go": zhFile,
			},
			pkg:     "p",
			def:     "en",
			wantErr: "重复定义",
		},
		{
			name: "文件名语言段非法",
			files: map[string]string{
				"messages_bad!.go": "package p\n\nvar M = map[string]string{\"K\": \"v\"}\n",
			},
			pkg:     "p",
			def:     "en",
			wantErr: "语言段",
		},
		{
			name: "文件语法错误",
			files: map[string]string{
				"messages_en.go": "package p\nvar (",
			},
			pkg:     "p",
			def:     "en",
			wantErr: "解析",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			for name, content := range tt.files {
				writeMsgFile(t, dir, name, content)
			}
			err := run(dir, tt.pkg, tt.def, "errors_gen.go")
			require.Error(t, err)
			assert.Contains(t, err.Error(), tt.wantErr)
		})
	}
}
