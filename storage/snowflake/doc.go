// Package snowflake 提供点分隔格式的雪花 ID 生成器：
//
//	"<毫秒时间戳>.<节点>.<序列>"，如 "1760001234567.23.4096"
//
// 三段对应经典雪花布局（41 位时间戳 + 10 位节点 + 12 位序列），时间戳段
// 为绝对 Unix 毫秒；以字符串存储（Oracle ID 列建议 VARCHAR2(32)），点分隔
// 便于人眼拆解各段与按时间排序。
//
// 业务系统启动时按实例设置节点号（多实例必须不同，否则可能重号）：
//
//	snowflake.SetNode(3)          // 全局默认生成器
//	id := snowflake.Next()        // "1760001234567.3.4096"
//
// 或自建实例：g := snowflake.New(3)。并发安全；时钟回拨时阻塞等待追平。
// 本包零三方依赖。
